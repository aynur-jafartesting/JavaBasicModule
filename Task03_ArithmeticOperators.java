public class Task03_ArithmeticOperators {
    public static void main(String[] args) {
        int a = 19, b = 5;

        System.out.println("a = " + a + ", b = " + b);
        System.out.println("a + b = " + (a + b));   // toplama
        System.out.println("a - b = " + (a - b));   // çıxma
        System.out.println("a * b = " + (a * b));   // vurma
        System.out.println("a / b = " + (a / b));   // int bölmə -> qalıq atılır
        System.out.println("a % b = " + (a % b));   // qalıq
            }
        }
